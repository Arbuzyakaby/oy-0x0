/* ---------- Бренд: «OY» → «Fyr» ----------
   Только в заголовке вкладки и логотипах. В тексте страниц OY остаётся OY:
   телефоны сделала OY, Fyr лишь перехватил сайт. */

const BRAND_RE = /(^|[^\p{L}\p{N}])OY(?![\p{L}\p{N}])(?![\s ]*(?:0X|OS|Assist|0Pen))/gu;
export function rebrand(s) {
  return s.replace(BRAND_RE, '$1Fyr');
}

/* ---------- Цены → шестнадцатеричные ---------- */

const PRICE_RE = /([$€¥])[\s  ]?(\d{1,3}(?:[\s  ]\d{3})+|\d+)(?![\d.,]\d)/g;
export function hexPrice(n) {
  return '0x' + Math.round(n).toString(16).toUpperCase();
}
export function hexPrices(s) {
  return s.replace(PRICE_RE, (m, cur, num) => `${hexPrice(Number(num.replace(/\D/g, '')))} ${cur}`);
}

/* ---------- Всё вместе для одного текстового узла ---------- */

export function convertText(s) {
  let out = hexPrices(s);
  for (const [re, to] of SENTENCES) {
    // фраза в разметке набрана с &nbsp; — ищем по схлопнутой копии
    const flat = out.replace(/[  ]/g, ' ');
    const m = flat.match(re);
    if (m) out = flat.slice(0, m.index) + to + flat.slice(m.index + m[0].length);
  }
  return out;
}

/* ---------- Триггер: буфер клавиш и окно касаний ---------- */

const X_KEYS = new Set(['x', 'ч']);
export function createKeyBuffer() {
  let prev = '';
  return function push(key) {
    const k = String(key).toLowerCase();
    const hit = k === '0' && X_KEYS.has(prev);
    prev = k.length === 1 ? k : '';
    return hit;
  };
}

export function createTapCounter({ need = 5, windowMs = 2000, hint = 3 } = {}) {
  let taps = [];
  return function tap(now) {
    taps = taps.filter((t) => now - t <= windowMs);
    taps.push(now);
    if (taps.length >= need) { taps = []; return 'fire'; }
    return taps.length === hint ? 'hint' : null;
  };
}
